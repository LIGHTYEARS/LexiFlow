import { z } from 'zod';

/**
 * Structured-output schemas for AI task results.
 *
 * Per technical-design/05 §4 (StructuredResultValidator) and §6 step 6:
 * only Zod-validated terminal states may be persisted or presented as a final
 * explanation. Streaming deltas are for display only and never satisfy these
 * schemas.
 *
 * These schemas define the contract the model MUST return. `generateObject`
 * enforces them at the SDK boundary; if the model returns something else the
 * task fails with INVALID_MODEL_OUTPUT rather than fabricating fields.
 */

/** Card type judged by the model. Mirrors domain CardType. */
export const AiCardTypeSchema = z.enum(['word', 'phrase', 'sentence', 'technical_term']);

/**
 * Quick-explain result — the first-screen explanation shown in the popover.
 * See PRD §7.3: type judgment + Chinese meaning + English meaning (+ optional
 * context meaning and examples for the expanded view §7.4).
 *
 * Fields beyond the first screen are optional so the model is not forced to
 * fabricate collocations/antonyms for content where they do not apply (§7.4).
 */
export const QuickExplainResultSchema = z.object({
  type: AiCardTypeSchema,
  chineseMeaning: z.string().min(1),
  englishMeaning: z.string().min(1),
  contextMeaning: z.string().optional(),
  examples: z.array(z.string()).max(5).optional(),
  collocations: z.array(z.string()).max(8).optional(),
  synonyms: z.array(z.string()).max(8).optional(),
  antonyms: z.array(z.string()).max(8).optional(),
  notes: z.string().optional(),
});

export type QuickExplainResult = z.infer<typeof QuickExplainResultSchema>;

/**
 * Full-analysis result — the expanded, type-appropriate analysis (§7.4, §8.1).
 * Type-specific detail lives under `details` as a light discriminated shape;
 * inapplicable fields are simply omitted.
 */
export const FullAnalysisResultSchema = z.object({
  type: AiCardTypeSchema,
  headword: z.string().min(1),
  chineseMeaning: z.string().min(1),
  englishMeaning: z.string().min(1),
  contextMeaning: z.string().optional(),
  examples: z.array(z.string()).max(8).optional(),
  collocations: z.array(z.string()).max(12).optional(),
  synonyms: z.array(z.string()).max(12).optional(),
  antonyms: z.array(z.string()).max(12).optional(),
  confusables: z.array(z.string()).max(12).optional(),
  register: z.string().optional(),
  domain: z.string().optional(),
  relatedConcepts: z.array(z.string()).max(12).optional(),
  translation: z.string().optional(),
  reusableStructure: z.array(z.string()).max(8).optional(),
  notes: z.string().optional(),
});

export type FullAnalysisResult = z.infer<typeof FullAnalysisResultSchema>;

/**
 * A single practice item generated by the model (§12.5).
 */
export const PracticeItemResultSchema = z.object({
  prompt: z.string().min(1),
  acceptableAnswers: z.array(z.string()).min(1),
  explanation: z.string().min(1),
  choices: z.array(z.string()).optional(),
  cardId: z.string().optional(),
});

export const PracticeGenerateResultSchema = z.object({
  items: z.array(PracticeItemResultSchema).min(1).max(20),
});

export type PracticeGenerateResult = z.infer<typeof PracticeGenerateResultSchema>;

/**
 * Registry mapping task type → its result schema.
 * The coordinator uses this to pick the schema for `generateObject`.
 */
export const AI_RESULT_SCHEMAS = {
  'quick-explain': QuickExplainResultSchema,
  'full-analysis': FullAnalysisResultSchema,
  'practice-generate': PracticeGenerateResultSchema,
} as const;

export type AiResultTaskType = keyof typeof AI_RESULT_SCHEMAS;
